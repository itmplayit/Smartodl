import { useEffect, useState } from 'react';
import { miscApi } from '../services/api';
import { useToast } from '../context/ToastContext';
import { Empty, Loader, Modal } from '../components/ui';
import { timeAgo } from '../utils/format';

const TYPES = [['activity', '📈 Platform activity'], ['users', '👥 User breakdown'], ['courses', '📘 Course performance'],
  ['coding', '💻 Coding submissions by difficulty'], ['quizzes', '🧠 Quiz performance'], ['contests', '🏆 Contest report']];

export default function ReportsManager() {
  const toast = useToast();
  const [rows, setRows] = useState(null);
  const [busy, setBusy] = useState('');
  const [view, setView] = useState(null);

  const load = async () => {
    try { const { data } = await miscApi.reports(); setRows(data.data); } catch (e) { toast.error(e.message); setRows([]); }
  };
  useEffect(() => { load(); }, []);

  const generate = async (type) => {
    setBusy(type);
    try {
      await miscApi.generateReport(type);
      toast.success('Report generated');
      load();
    } catch (e) { toast.error(e.message); } finally { setBusy(''); }
  };

  const parse = (payload) => {
    if (!payload) return [];
    if (Array.isArray(payload)) return payload;
    try { const p = JSON.parse(payload); return Array.isArray(p) ? p : [p]; } catch { return []; }
  };

  return (
    <div className="container section">
      <div className="between wrap mb">
        <div><span className="eyebrow">Analytics</span><h2>Reports</h2>
          <p className="muted small" style={{ marginBottom: 0 }}>Generate and archive reports from live platform data.</p></div>
        <button className="btn btn-ghost" onClick={load}>🔄 Refresh</button>
      </div>

      <div className="card mb">
        <h3>Generate a report</h3>
        <div className="row wrap" style={{ gap: 10 }}>
          {TYPES.map(([type, label]) => (
            <button key={type} className="btn btn-ghost" disabled={busy === type} onClick={() => generate(type)}>
              {busy === type ? 'Generating…' : label}
            </button>
          ))}
        </div>
        <p className="tiny muted mt-s">Each report snapshots the current numbers and stores them for later download/inspection.</p>
      </div>

      {!rows && <Loader label="Loading reports…" />}
      {rows && rows.length === 0 && <Empty title="No reports generated yet" hint="Pick a report type above to create the first snapshot." />}

      {rows && rows.length > 0 && (
        <div className="table-wrap" tabIndex={0}>
          <table className="table">
            <thead><tr><th>#</th><th>Title</th><th>Type</th><th>Period</th><th>Generated by</th><th>When</th><th><span className="sr-only">Actions</span></th></tr></thead>
            <tbody>
              {rows.map((r) => (
                <tr key={r.id}>
                  <td className="small muted">{r.id}</td>
                  <td><strong>{r.title}</strong><div className="tiny muted">{r.description}</div></td>
                  <td><span className="tag">{r.report_type}</span></td>
                  <td className="tiny muted">{String(r.period_start || '').slice(0, 10)} → {String(r.period_end || '').slice(0, 10)}</td>
                  <td className="small">{r.generated_by_name || 'system'}</td>
                  <td className="tiny muted">{timeAgo(r.created_at)}</td>
                  <td><button className="btn btn-sm btn-ghost" onClick={() => setView(r)}>👁 View</button></td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      <Modal open={!!view} title={view ? view.title : ''} onClose={() => setView(null)} wide>
        {view && (
          <>
            <p className="small muted">{view.description} • generated {timeAgo(view.created_at)}</p>
            <div className="table-wrap" tabIndex={0}>
              <table className="table">
                <thead><tr>{Object.keys(parse(view.payload)[0] || {}).map((k) => <th key={k}>{k.replace(/_/g, ' ')}</th>)}</tr></thead>
                <tbody>
                  {parse(view.payload).map((row, i) => (
                    <tr key={i}>{Object.values(row).map((v, j) => <td key={j} className="small">{String(v)}</td>)}</tr>
                  ))}
                </tbody>
              </table>
            </div>
            <div className="row mt" style={{ justifyContent: 'flex-end' }}>
              <button className="btn btn-ghost" onClick={() => {
                const blob = new Blob([JSON.stringify(parse(view.payload), null, 2)], { type: 'application/json' });
                const a = document.createElement('a');
                a.href = URL.createObjectURL(blob);
                a.download = `${view.report_type}-report-${view.id}.json`;
                a.click();
              }}>⬇ Download JSON</button>
            </div>
          </>
        )}
      </Modal>
    </div>
  );
}
