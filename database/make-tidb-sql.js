#!/usr/bin/env node
'use strict';
/**
 * education_platform.sql  ->  education_platform.tidb.sql
 *
 * mysqldump output is intended for MariaDB/MySQL. TiDB Cloud and
 * managed MySQL services such as PlanetScale reject parts of that output.
 * This script removes those parts. It does not modify the original file,
 * so local XAMPP imports continue to use the original.
 *
 * What it removes or changes, and why:
 *
 *  1. CREATE DATABASE / USE
 *     In TiDB Cloud, imports run inside an existing database, and
 *     CREATE DATABASE permission is usually unavailable. Keeping this line
 *     either causes an error or sends all data to the wrong database.
 *
 *  2. LOCK TABLES / UNLOCK TABLES
 *     These statements are only a mysqldump performance optimisation and do not affect the data.
 *     Table locking is disabled by default in TiDB.
 *
 *  3. MariaDB-only conditional comments
 *     Only MariaDB understands these comments; they are useless elsewhere.
 *
 *  4. FOREIGN_KEY_CHECKS is moved out of its executable comment
 *     and emitted as a plain SET statement so TiDB reliably honours it.
 *     There are 50 foreign keys and the tables appear alphabetically, so
 *     without disabling the checks the import fails part-way through.
 *
 *  The collation (utf8mb4_unicode_ci) is already portable across TiDB, MySQL 5.7+,
 *  and every MariaDB release. utf8mb4_uca1400_ai_ci (the MariaDB 11.5+
 *  default) does not exist in TiDB, so every CREATE TABLE in the source
 *  specifies COLLATE explicitly.
 *
 * Usage:  node database/make-tidb-sql.js
 */
const fs = require('fs');
const path = require('path');

const dir = __dirname;
const src = path.join(dir, 'education_platform.sql');
const out = path.join(dir, 'education_platform.tidb.sql');

if (!fs.existsSync(src)) {
  console.error(`[tidb] ${src} was not found`);
  process.exit(1);
}

const lines = fs.readFileSync(src, 'utf8').split('\n');
const kept = [];
const dropped = { database: 0, lock: 0, mariadb: 0 };

for (const line of lines) {
  const t = line.trim();
  if (/^CREATE DATABASE\b/i.test(t) || /^USE\s+`?[A-Za-z0-9_]+`?\s*;/i.test(t)) { dropped.database += 1; continue; }
  if (/^(UN)?LOCK\s+TABLES\b/i.test(t)) { dropped.lock += 1; continue; }
  if (/^\/\*M!/.test(t)) { dropped.mariadb += 1; continue; }
  kept.push(line);
}

let sql = kept.join('\n');

// FK checks: conditional comment -> plain statement
sql = sql.replace(
  /\/\*!40014 SET @OLD_FOREIGN_KEY_CHECKS=@@FOREIGN_KEY_CHECKS, FOREIGN_KEY_CHECKS=0 \*\/;/,
  'SET FOREIGN_KEY_CHECKS = 0;',
);
sql = sql.replace(
  /\/\*!40014 SET FOREIGN_KEY_CHECKS=@OLD_FOREIGN_KEY_CHECKS \*\/;/g,
  'SET FOREIGN_KEY_CHECKS = 1;',
);

const header = [
  '-- SmartODL schema prepared for TiDB Cloud / managed MySQL.',
  '-- This file is generated by `node database/make-tidb-sql.js`; do not edit it manually.',
  '-- In TiDB Cloud: select your database, then run this entire file.',
  '-- This file contains no CREATE DATABASE statement; tables are created in the database you select.',
  '',
].join('\n');

fs.writeFileSync(out, header + sql);

console.log(`[tidb] written: ${path.relative(process.cwd(), out)}`);
console.log(`[tidb] removed -> CREATE DATABASE/USE: ${dropped.database}`
  + `, LOCK/UNLOCK TABLES: ${dropped.lock}, MariaDB-only comments: ${dropped.mariadb}`);
